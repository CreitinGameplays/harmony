#!/usr/bin/env python3
"""Generate the ld(1) argument template used by the native LLVM-C backend.

The final compiler links executables without spawning clang. This script runs
clang once at *build time* with -### to discover the correct crt/libc/loader
paths for the host, then stores the resulting ld command as one token per
line. <OUT>, <LLVMC>, <HOSTRT>, <HOSTMAIN> and <OBJ> are replaced by the compiler at
run time. No toolchain path is hardcoded in the compiler sources.
"""
import os
import shlex
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "build", "host-link.txt")


def main():
    libdir = subprocess.check_output(["llvm-config", "--libdir"], text=True).strip()
    major = subprocess.check_output(["llvm-config", "--version"], text=True).strip().split(".")[0]
    dummy_c = os.path.join(ROOT, "build", "hostlink-dummy.c")
    dummy_o = os.path.join(ROOT, "build", "hostlink-dummy.o")
    dummy_out = os.path.join(ROOT, "build", "hostlink-dummy.out")
    os.makedirs(os.path.dirname(dummy_c), exist_ok=True)
    with open(dummy_c, "w") as f:
        f.write("int main(void) { return 0; }\n")
    subprocess.check_call(["clang", "-c", dummy_c, "-o", dummy_o])
    cmd = [
        "clang", "-###", dummy_o, "-o", dummy_out,
        "-L" + libdir, "-Wl,-rpath," + libdir, "-lLLVM-" + major,
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    ld_line = None
    for line in proc.stderr.splitlines() + proc.stdout.splitlines():
        if "ld" not in line:
            continue
        try:
            tokens = shlex.split(line)
        except ValueError:
            continue
        if not tokens or os.path.basename(tokens[0]) != "ld":
            continue
        if "-o" in tokens:
            ld_line = tokens
    if ld_line is None:
        sys.exit("could not find the ld command from clang -###")
    tokens = []
    i = 0
    while i < len(ld_line):
        tok = ld_line[i]
        if tok == "-o" and i + 1 < len(ld_line):
            tokens.extend(["-o", "<OUT>"])
            i += 2
            continue
        if tok == dummy_o:
            tokens.extend(["<LLVMC>", "<HOSTRT>", "<HOSTMAIN>", "<OBJ>"])
        elif tok == dummy_out:
            pass
        else:
            tokens.append(tok)
        i += 1
    for needle in ("<LLVMC>", "<HOSTRT>", "<HOSTMAIN>", "<OBJ>", "<OUT>"):
        if needle not in tokens:
            sys.exit("generated ld command is missing " + needle)
    with open(OUT, "w") as f:
        f.write("# generated by tools/gen-hostlink.py; do not edit\n")
        for tok in tokens:
            f.write(tok + "\n")
    os.remove(dummy_c)
    os.remove(dummy_o)
    print("wrote " + OUT)


if __name__ == "__main__":
    main()
